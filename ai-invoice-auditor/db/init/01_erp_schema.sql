-- erp schema: owned by mock-erp (read-only via HTTP). Seeded from provided JSON.
CREATE SCHEMA IF NOT EXISTS erp;
CREATE TABLE erp.vendors (vendor_id VARCHAR(16) PRIMARY KEY, vendor_name VARCHAR(255) NOT NULL, country VARCHAR(64), currency CHAR(3) NOT NULL);
CREATE TABLE erp.sku_master (item_code VARCHAR(32) PRIMARY KEY, category VARCHAR(64), uom VARCHAR(16), gst_rate NUMERIC(5,2));
CREATE TABLE erp.purchase_orders (po_number VARCHAR(32) PRIMARY KEY, vendor_id VARCHAR(16) NOT NULL REFERENCES erp.vendors(vendor_id));
CREATE TABLE erp.po_line_items (id SERIAL PRIMARY KEY, po_number VARCHAR(32) REFERENCES erp.purchase_orders(po_number), item_code VARCHAR(32) REFERENCES erp.sku_master(item_code), description TEXT, qty NUMERIC(12,3), unit_price NUMERIC(14,4), currency CHAR(3));
